//! Node policy and public trust material. CA private keys never enter resolved
//! server options, node resources, snapshots, or subscriber projections.
use anyhow::{Context, Result, ensure};
use chrono::{DateTime, Duration, Utc};
use serde::{Deserialize, Serialize};
use serde_json::{Value, json};
use sha2::{Digest, Sha256};
use sqlx::{PgPool, Postgres, Row, Transaction};

use super::ca::Authority;
use crate::{api::resources::ResourceFile, security::SecretBox};

#[derive(Clone, Debug, Default, Deserialize, Serialize, PartialEq, Eq)]
#[serde(tag = "mode", rename_all = "snake_case", deny_unknown_fields)]
pub enum Settings {
    #[default]
    Off,
    Managed {
        ca_credential_id: String,
        ca_credential_version: i64,
    },
}
impl Settings {
    pub fn from_config(config: &Value) -> Result<Self> {
        if let Some(value) = config.get("mtls") {
            let object = value.as_object().context("mtls must be an object")?;
            let allowed: &[&str] = match value["mode"].as_str() {
                Some("off") => &["mode"],
                Some("managed") => &["mode", "ca_credential_id", "ca_credential_version"],
                _ => anyhow::bail!("mtls.mode must be off or managed"),
            };
            ensure!(
                object.keys().all(|field| allowed.contains(&field.as_str())),
                "unexpected mtls policy field"
            );
        }
        let policy: Self = match config.get("mtls") {
            Some(value) => serde_json::from_value(value.clone())
                .context("mtls must be off or managed with an exact CA reference")?,
            None => Self::Off,
        };
        if let Self::Managed {
            ca_credential_id,
            ca_credential_version,
        } = &policy
        {
            ensure!(
                uuid::Uuid::parse_str(ca_credential_id).is_ok() && *ca_credential_version > 0,
                "invalid managed CA reference"
            );
            ensure!(
                (config.get("tls").is_some() || config.get("acme").is_some())
                    && !(config.get("tls").is_some() && config.get("acme").is_some()),
                "managed mTLS requires TLS or ACME certificates"
            );
        }
        Ok(policy)
    }
    pub fn authority(&self) -> Option<(&str, i64)> {
        match self {
            Self::Off => None,
            Self::Managed {
                ca_credential_id,
                ca_credential_version,
            } => Some((ca_credential_id, *ca_credential_version)),
        }
    }
}

pub fn validate_input(config: &mut Value) -> Result<Settings> {
    ensure!(
        config.pointer("/tls/clientCA").is_none(),
        "tls.clientCA is generated by the server; select a managed CA identity"
    );
    let settings = Settings::from_config(config)?;
    config
        .as_object_mut()
        .context("server config must be an object")?
        .insert("mtls".into(), serde_json::to_value(&settings)?);
    Ok(settings)
}

pub async fn validate_binding(
    pool: &PgPool,
    secrets: &SecretBox,
    settings: &Settings,
    new_binding: bool,
) -> Result<()> {
    let Some((id, version)) = settings.authority() else {
        return Ok(());
    };
    let (kind, owner, archived, payload, _) = super::load(pool, secrets, id, version).await?;
    ensure!(
        kind == "ca_identity" && owner.is_none() && !archived,
        "an active CA identity is required"
    );
    let authority = Authority::from_payload(&payload, Utc::now())?;
    if new_binding {
        authority.validate_new_binding(Utc::now())?;
    }
    Ok(())
}

pub async fn check_binding(
    tx: &mut Transaction<'_, Postgres>,
    settings: &Settings,
    new_binding: bool,
) -> Result<()> {
    let Some((id, version)) = settings.authority() else {
        return Ok(());
    };
    let row=sqlx::query("SELECT a.published_version,c.archived,g.expires_at FROM mtls_authorities a JOIN credentials c ON c.id=a.credential_id JOIN mtls_ca_generations g ON g.ca_id=a.credential_id AND g.ca_version=a.published_version WHERE a.credential_id=$1 AND c.kind='ca_identity'")
        .bind(id).fetch_optional(&mut **tx).await?.context("CA identity does not exist")?;
    ensure!(
        !row.get::<bool, _>("archived") && row.get::<i64, _>("published_version") == version,
        "CA published version changed; reload the node and select its current published version"
    );
    let minimum = Utc::now()
        + if new_binding {
            Duration::days(30)
        } else {
            Duration::zero()
        };
    ensure!(
        row.get::<DateTime<Utc>, _>("expires_at") > minimum,
        "CA has insufficient remaining validity"
    );
    Ok(())
}

pub async fn save_target(
    tx: &mut Transaction<'_, Postgres>,
    node: &str,
    revision: i64,
    settings: &Settings,
) -> Result<()> {
    sqlx::query(
        "UPDATE mtls_node_trust SET desired=FALSE,revision=revision+1 WHERE node_id=$1 AND desired",
    )
    .bind(node)
    .execute(&mut **tx)
    .await?;
    if let Some((id, version)) = settings.authority() {
        sqlx::query("INSERT INTO mtls_node_trust(node_id,ca_id,ca_version,desired) VALUES($1,$2,$3,TRUE) ON CONFLICT(node_id,ca_id,ca_version) DO UPDATE SET desired=TRUE,revision=mtls_node_trust.revision+1")
            .bind(node).bind(id).bind(version).execute(&mut **tx).await?;
        sqlx::query("INSERT INTO mtls_rotation_nodes(rotation_id,node_id,expected_revision) SELECT id,$2,$3 FROM mtls_rotations WHERE ca_id=$1 AND phase<>'complete' ON CONFLICT(rotation_id,node_id) DO UPDATE SET expected_revision=$3,trust_prepared=FALSE,probe_switched=FALSE")
            .bind(id).bind(node).bind(revision).execute(&mut **tx).await?;
    }
    super::authorization::reconcile_node(tx, node, false).await?;
    Ok(())
}

#[derive(Clone, Debug, Deserialize, Serialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct TrustVersion {
    pub ca_id: String,
    pub version: i64,
}

pub async fn desired_trust(
    pool: &PgPool,
    node: &str,
    settings: &Settings,
) -> Result<Vec<TrustVersion>> {
    let Some((id, version)) = settings.authority() else {
        return Ok(vec![]);
    };
    let rows=sqlx::query("SELECT g.ca_version FROM mtls_ca_generations g WHERE g.ca_id=$1 AND (g.ca_version=$2 OR g.state IN ('published','preparing') OR EXISTS(SELECT 1 FROM mtls_user_versions v WHERE v.ca_id=g.ca_id AND v.ca_version=g.ca_version AND v.expires_at>now()-interval '5 minutes') OR EXISTS(SELECT 1 FROM mtls_probe_versions p WHERE p.ca_id=g.ca_id AND p.ca_version=g.ca_version AND p.expires_at>now()-interval '5 minutes') OR EXISTS(SELECT 1 FROM mtls_node_trust t WHERE t.node_id=$3 AND t.ca_id=g.ca_id AND t.ca_version=g.ca_version AND t.deployed) OR EXISTS(SELECT 1 FROM mtls_live_activation_trust a WHERE a.node_id=$3 AND a.ca_id=g.ca_id AND a.ca_version=g.ca_version)) ORDER BY g.ca_version")
        .bind(id).bind(version).bind(node).fetch_all(&mut *crate::read_snapshot::begin(pool).await?).await?;
    ensure!(!rows.is_empty(), "managed CA generation is unavailable");
    Ok(rows
        .into_iter()
        .map(|row| TrustVersion {
            ca_id: id.into(),
            version: row.get("ca_version"),
        })
        .collect())
}

pub async fn materialize(
    pool: &PgPool,
    config: &Value,
    trust: &[TrustVersion],
) -> Result<(Value, Option<ResourceFile>)> {
    let settings = Settings::from_config(config)?;
    let mut resolved = crate::node_acme::compile(config)?;
    if settings == Settings::Off {
        return Ok((resolved, None));
    }
    let selected = settings.authority().context("managed CA required")?.0;
    ensure!(
        !trust.is_empty() && trust.iter().all(|v| v.ca_id == selected),
        "trust set must belong to the selected CA identity"
    );
    let mut pem = String::new();
    for item in trust {
        let metadata:Value=sqlx::query_scalar("SELECT metadata FROM credential_versions v JOIN credentials c ON c.id=v.credential_id WHERE v.credential_id=$1 AND v.version=$2 AND c.kind='ca_identity'")
            .bind(&item.ca_id).bind(item.version).fetch_one(&mut *crate::read_snapshot::begin(pool).await?).await?;
        pem.push_str(
            metadata["trust_anchor_certificate"]
                .as_str()
                .context("CA trust anchor is unavailable")?,
        );
    }
    let id = format!(
        "mtls-trust-{}.crt",
        hex::encode(Sha256::digest(pem.as_bytes()))
    );
    resolved["tls"]["clientCA"] = json!(format!("/etc/hysteriax/resources/{id}"));
    Ok((
        resolved,
        Some(ResourceFile {
            id,
            content: pem.into_bytes(),
        }),
    ))
}

pub async fn preview(pool: &PgPool, node: &str, config: &Value) -> Result<Value> {
    let policy = Settings::from_config(config)?;
    let trust = desired_trust(pool, node, &policy).await?;
    Ok(materialize(pool, config, &trust).await?.0)
}

/// Monitoring and deployment use a node-owned probe; no user assignment is needed.
pub async fn probe_material(
    pool: &PgPool,
    secrets: &SecretBox,
    node: &str,
    ca: &str,
    version: Option<i64>,
) -> Result<Option<(String, String)>> {
    let row=sqlx::query("SELECT p.credential_id,p.credential_version FROM mtls_probe_versions p WHERE p.node_id=$1 AND p.ca_id=$2 AND ($3::bigint IS NULL OR p.ca_version=$3) AND NOT p.discarded AND p.expires_at>$4 AND ($3::bigint IS NOT NULL OR EXISTS(SELECT 1 FROM mtls_active_probes active JOIN mtls_node_trust t ON t.node_id=active.node_id AND t.ca_id=active.ca_id AND t.ca_version=active.ca_version WHERE active.node_id=p.node_id AND active.credential_id=p.credential_id AND active.credential_version=p.credential_version AND t.deployed)) ORDER BY p.ca_version DESC,p.credential_version DESC LIMIT 1")
        .bind(node).bind(ca).bind(version).bind(Utc::now()).fetch_optional(pool).await?;
    let Some(row) = row else { return Ok(None) };
    let (kind, owner, _, payload, _) = super::load(
        pool,
        secrets,
        &row.get::<String, _>("credential_id"),
        row.get("credential_version"),
    )
    .await?;
    ensure!(
        kind == "tls_identity" && owner.is_none(),
        "invalid node probe identity"
    );
    Ok(Some((
        super::text(&payload, "certificate")?.into(),
        super::text(&payload, "private_key")?.into(),
    )))
}

pub async fn prepare_users(
    pool: &PgPool,
    secrets: &SecretBox,
    node: &str,
    settings: &Settings,
    trust: &[TrustVersion],
    rollback: bool,
) -> Result<()> {
    let Some((ca, version)) = settings.authority() else {
        return Ok(());
    };
    let expected: i64 = sqlx::query_scalar("SELECT desired_revision FROM nodes WHERE id=$1")
        .bind(node)
        .fetch_one(pool)
        .await?;
    let users: Vec<String> = sqlx::query_scalar(
        "SELECT user_id FROM node_assignments WHERE node_id=$1 ORDER BY user_id",
    )
    .bind(node)
    .fetch_all(pool)
    .await?;
    let mut candidates = Vec::new();
    if rollback {
        let valid_ca:bool=sqlx::query_scalar("SELECT EXISTS(SELECT 1 FROM mtls_ca_generations g JOIN credentials c ON c.id=g.ca_id WHERE g.ca_id=$1 AND g.ca_version=$2 AND g.expires_at>now() AND NOT c.archived)").bind(ca).bind(version).fetch_one(pool).await?;
        ensure!(
            valid_ca,
            "rollback unavailable: historical CA expired or was archived; rebuild or sync the node"
        );
        let versions: Vec<i64> = trust.iter().map(|v| v.version).collect();
        for user in &users {
            let valid:bool=sqlx::query_scalar("SELECT EXISTS(SELECT 1 FROM mtls_user_identities i JOIN mtls_user_versions v ON v.identity_id=i.id WHERE i.user_id=$1 AND i.ca_id=$2 AND NOT i.archived AND v.ca_version=ANY($3) AND v.released AND NOT v.discarded AND v.not_before<=now() AND v.expires_at>now())")
                .bind(user).bind(ca).bind(&versions).fetch_one(pool).await?;
            ensure!(
                valid,
                "rollback unavailable: a currently authorized user has no valid historical shared identity; rebuild or sync the node"
            );
        }
        return Ok(());
    }
    for user in &users {
        candidates
            .push(super::identities::prepare_user(pool, secrets, user, ca, version, false).await?);
    }
    let mut tx = crate::db::begin_write(pool).await?;
    let current: Option<i64> = sqlx::query_scalar("SELECT desired_revision FROM nodes WHERE id=$1")
        .bind(node)
        .fetch_optional(&mut *tx)
        .await?;
    let current_users: Vec<String> = sqlx::query_scalar(
        "SELECT user_id FROM node_assignments WHERE node_id=$1 ORDER BY user_id",
    )
    .bind(node)
    .fetch_all(&mut *tx)
    .await?;
    ensure!(
        current == Some(expected) && current_users == users,
        "node permissions changed during signing; retry deployment"
    );
    for candidate in candidates {
        super::identities::commit_user(&mut tx, secrets, candidate).await?;
    }
    tx.commit().await?;
    Ok(())
}
