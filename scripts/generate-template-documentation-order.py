#!/usr/bin/env python3
"""Generate presentation metadata from the immutable sing-box 1.14.2 documentation.
Usage: python3 scripts/generate-template-documentation-order.py SOURCE/docs/configuration [--check]
Both English and Chinese files may be present; English field identifiers are canonical.
Example values never become defaults. Ambiguous duplicate anchors link to the page.
"""
import argparse
import collections
import hashlib
import json
import pathlib
import re

SCHEMA_SHA256 = '15133dc518142b7082f120fa7ed08dabb5b28768850e4bebcde67272cbd58d47'
DOCUMENTATION_SHA256 = '550f8358d23bd270a3806912a2fdec06b85753be1dcf61875318ad4151fa9933'
FIELD_HEADING = re.compile(r'^#{3,6} +`?([a-z][a-zA-Z0-9_]*(?:\.[a-zA-Z0-9_]+)*`?(?:, *`?[a-z][a-zA-Z0-9_.]*`?)*)\s*$', re.M)


def extract(document):
    """Return unique fields and anchor overrides, including grouped headings."""
    occurrences = []
    for match in FIELD_HEADING.finditer(document):
        heading = match.group(1).replace('`', '')
        keys = [key.strip() for key in heading.split(',')]
        anchor = re.sub(r'[^\w\- ]', '', heading).replace(' ', '-').lower()
        occurrences.extend((key, anchor) for key in keys)
    counts = collections.Counter(key for key, _ in occurrences)
    fields = list(dict.fromkeys(key for key, _ in occurrences))
    anchors = {key: '' if counts[key] > 1 else anchor for key, anchor in occurrences
               if counts[key] > 1 or anchor != key.replace('.', '').lower()}
    return fields, anchors


def verify_source(source):
    upstream_schema = source.parent / 'schema.json'
    if not upstream_schema.is_file() or hashlib.sha256(upstream_schema.read_bytes()).hexdigest() != SCHEMA_SHA256:
        raise ValueError('Expected v1.14.2 docs/schema.json (checksum mismatch or missing)')
    digest = hashlib.sha256()
    for document in sorted(source.rglob('*.md')):
        if document.name.endswith('.zh.md'): continue
        digest.update(document.relative_to(source).as_posix().encode() + b'\0' + document.read_bytes() + b'\0')
    if digest.hexdigest() != DOCUMENTATION_SHA256:
        raise ValueError('Expected the complete, unchanged v1.14.2 English documentation tree')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=pathlib.Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        verify_source(args.source)
    except ValueError as error:
        parser.error(str(error))
    orders, anchors = {}, {}
    for document in sorted(args.source.rglob('*.md')):
        if document.name.endswith('.zh.md'):
            continue
        page = document.relative_to(args.source).with_suffix('').as_posix()
        if page.endswith('/index'):
            page = page[:-6]
        fields, overrides = extract(document.read_text())
        if fields:
            orders[page] = ' '.join(fields)
        if overrides:
            anchors[page] = overrides
    if len(orders) < 90:
        parser.error('Incomplete documentation tree: expected at least 90 pages with field headings')
    output = pathlib.Path(__file__).resolve().parents[1] / 'apps/macos/Sources/HysteriaX/Models/TemplateDocumentationOrder.swift'
    lines = [
        '// Generated by scripts/generate-template-documentation-order.py.',
        '// Source: https://github.com/SagerNet/sing-box/tree/v1.14.2/docs/configuration',
        '// Field identifiers only. Examples are deliberately not treated as defaults.',
        'enum TemplateDocumentationOrder {',
        '    static let pages: [String: String] = [',
    ]
    lines += ['        ' + json.dumps(page) + ': ' + json.dumps(fields) + ',' for page, fields in orders.items()]
    lines += ['    ]', '    // Empty anchors indicate repeated headings whose generated suffix is ambiguous.', '    static let anchors: [String: [String: String]] = [']
    lines += ['        ' + json.dumps(page) + ': [' + ', '.join(json.dumps(k) + ': ' + json.dumps(v) for k, v in fields.items()) + '],' for page, fields in anchors.items()]
    lines += ['    ]', '}', '']
    generated = '\n'.join(lines)
    if args.check:
        if not output.is_file() or output.read_text() != generated:
            raise SystemExit('Documentation metadata is stale; regenerate before building')
    else:
        output.write_text(generated)
    print(f'{len(orders)} pages, {sum(len(fields.split()) for fields in orders.values())} distinct page fields; metadata ' + ('verified' if args.check else 'generated'))


if __name__ == '__main__':
    main()
